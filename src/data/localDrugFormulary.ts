const SAMPLE_MEDS_BY_ID = new Map<string, MedicationItem>();
for (const c of SAMPLE_CASES) {
  for (const med of c.medications) {
    SAMPLE_MEDS_BY_ID.set(med.id, med);
  }
}

function fromSample(
  sampleId: string,
  id: string,
  category: Exclude<FormularyCategory, 'all'>,
  keywords: string[]
): FormularyDrugRecord {
  const base = SAMPLE_MEDS_BY_ID.get(sampleId)!;
  return {
    ...base,
    id,
    sourceType: 'manual',
    category,
    keywords,
    dosing: {
      ...base.dosing,
      prescribedRegimen: undefined,
    },
  };
}

